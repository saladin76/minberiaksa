#!/usr/bin/env node
/**
 * Vendor the identity fonts so the build never asks Google for them.
 *
 * `next/font/google` downloads each face at build time, and under Turbopack a
 * failed download surfaces as
 *   Module not found: Can't resolve '@vercel/turbopack-next/internal/font/google/font'
 * which took a production deploy down (Sept 2026). The fonts are now static
 * files under `public/fonts/` with a plain stylesheet
 * (`styles/self-hosted-fonts.css`), and the root layout sets the same CSS
 * variables the `next/font` objects used to.
 *
 * Re-run to refresh: fetches the CSS2 stylesheet Google serves to a modern
 * browser (woff2 + unicode-range subsets), keeps only the subsets the site
 * uses, downloads each file once and rewrites the stylesheet to point at it.
 *   node scripts/vendor-google-fonts.mjs
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";

const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124 Safari/537.36";
const KEEP_SUBSETS = new Set(["latin", "latin-ext", "arabic"]);

/* Same families and weights `app/layout.tsx` loaded through next/font/google.
   Cairo and Montserrat are variable fonts: one file per subset covers every
   weight, so they are asked for as a range. */
const FAMILIES = [
  { family: "Cairo", query: "Cairo:wght@200..1000", dir: "cairo" },
  { family: "Montserrat", query: "Montserrat:wght@100..900", dir: "montserrat" },
  { family: "Amiri", query: "Amiri:wght@400;700", dir: "amiri" },
  { family: "Poppins", query: "Poppins:wght@400;500;600;700", dir: "poppins" },
  { family: "Tajawal", query: "Tajawal:wght@400;500;700", dir: "tajawal" },
];

async function fetchCss(query) {
  const res = await fetch(`https://fonts.googleapis.com/css2?family=${query}&display=swap`, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`css ${query}: HTTP ${res.status}`);
  return res.text();
}

/** Split the stylesheet into `/* subset *​/ @font-face { … }` blocks. */
function faces(css) {
  const out = [];
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
  let m;
  while ((m = re.exec(css))) out.push({ subset: m[1], block: m[2] });
  return out;
}

const cssOut = [
  "/* Generated by scripts/vendor-google-fonts.mjs — do not edit by hand.",
  " * The identity fonts, self-hosted from public/fonts/ so the build never",
  " * fetches them from Google (see the script header for why). */",
  "",
];
const seen = new Map();
let files = 0;

for (const f of FAMILIES) {
  const css = await fetchCss(f.query);
  mkdirSync(`public/fonts/${f.dir}`, { recursive: true });
  for (const face of faces(css)) {
    if (!KEEP_SUBSETS.has(face.subset)) continue;
    const url = face.block.match(/url\(([^)]+)\)/)?.[1];
    const weight = face.block.match(/font-weight:\s*([^;]+);/)?.[1].trim().replace(/\s+/g, "-") ?? "400";
    if (!url) continue;
    let local = seen.get(url);
    if (!local) {
      const res = await fetch(url, { headers: { "User-Agent": UA } });
      if (!res.ok) throw new Error(`font ${url}: HTTP ${res.status}`);
      const bytes = Buffer.from(await res.arrayBuffer());
      const hash = createHash("sha1").update(bytes).digest("hex").slice(0, 8);
      local = `/fonts/${f.dir}/${f.dir}-${weight}-${face.subset}-${hash}.woff2`;
      writeFileSync(`public${local}`, bytes);
      seen.set(url, local);
      files += 1;
    }
    cssOut.push(`/* ${f.family} ${face.subset} */`);
    cssOut.push(face.block.replace(url, local));
    cssOut.push("");
  }
}

writeFileSync("styles/self-hosted-fonts.css", `${cssOut.join("\n")}\n`, "utf8");
console.log(`[vendor-google-fonts] ${files} files under public/fonts, stylesheet at styles/self-hosted-fonts.css`);
