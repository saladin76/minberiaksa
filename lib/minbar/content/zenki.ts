/**
 * The Nur ad-Din Zangi course syllabus — carried verbatim from
 * `Minbar/دورة نور الدين زنكي.dc.html`.
 *
 * TRANSLATION GAP, and a deliberate one. Every label on the page — the section
 * headings, "topics of the session", "the trainee aims to", "references" — is a
 * reviewed key in the `zenki` namespace and is translated in all 19 languages.
 * The syllabus itself is not, and is not translated here either.
 *
 * Two reasons. The course is delivered in Arabic, so its syllabus describes
 * Arabic-language sessions. And the content is scholarly: unit topics, learning
 * objectives, and a bibliography of Arabic works with their authors, editions
 * and publishers. Translating that is a specialist task, and a wrong rendering
 * of a book title or a scholar's name is worse than the Arabic standing as it
 * is. The page marks these blocks `lang="ar" dir="rtl"` so they render and are
 * announced correctly inside a page read in any other language.
 */

